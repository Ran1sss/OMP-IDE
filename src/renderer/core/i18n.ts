/** RU three-form rule: 1 файл / 2 файла / 5 файлов */
export function ru3(n: number, one: string, few: string, many: string): string {
  const a = Math.abs(n) % 100;
  const b = a % 10;
  if (a > 10 && a < 20) return many;
  if (b === 1) return one;
  if (b >= 2 && b <= 4) return few;
  return many;
}

/** EN two-form rule: 1 file / 2 files */
export function en2(n: number, one: string, many: string): string {
  return Math.abs(n) === 1 ? one : many;
}

