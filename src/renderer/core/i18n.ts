/** locale-correct relative time: «4 минуты назад» / “4 minutes ago” */
export function relTime(epochMs: number): string {
  const s = Math.max(0, Math.floor((Date.now() - epochMs) / 1000));
  const min = Math.floor(s / 60);
  const h = Math.floor(min / 60);
  const d = Math.floor(h / 24);
  if (current === "ru") {
    if (s < 45) return "только что";
    if (min < 60) return `${Math.max(1, min)} ${ru3(Math.max(1, min), "минуту", "минуты", "минут")} назад`;
    if (h < 24) return `${h} ${ru3(h, "час", "часа", "часов")} назад`;
    if (d === 1) return "вчера";
    if (d < 30) return `${d} ${ru3(d, "день", "дня", "дней")} назад`;
    const dt = new Date(epochMs);
    return `${String(dt.getDate()).padStart(2, "0")}.${String(dt.getMonth() + 1).padStart(2, "0")}.${dt.getFullYear()}`;
  }
  if (s < 45) return "just now";
  if (min < 60) return `${Math.max(1, min)} ${en2(Math.max(1, min), "minute", "minutes")} ago`;
  if (h < 24) return `${h} ${en2(h, "hour", "hours")} ago`;
  if (d === 1) return "yesterday";
  if (d < 30) return `${d} ${en2(d, "day", "days")} ago`;
  const dt = new Date(epochMs);
  return dt.toISOString().slice(0, 10);
}

